import assert from 'node:assert/strict';
import { validateExpressionTracks, expressionWeight } from '../src/facial-expressions.js';
import { createCharacterEntry } from '../src/scenes.js';
const tracks = [{ expression: 'happy', keys: [{ t: 1, weight: 0 }, { t: 3, weight: 1 }, { t: 4, weight: 0 }] }];
assert.equal(expressionWeight(tracks[0].keys, 0), 0);
assert.equal(expressionWeight(tracks[0].keys, 2), 0.5);
assert.equal(expressionWeight(tracks[0].keys, 3.5), 0.5);
assert.equal(expressionWeight(tracks[0].keys, 10), 0);
assert.equal(expressionWeight(tracks[0].keys, 2), 0.5, 'reverse seeking has no accumulated state');
assert.throws(() => validateExpressionTracks(tracks, ['sad']), /unavailable/);
for (const keys of [[{t:0,weight:2}], [{t:-1,weight:0}], [{t:NaN,weight:0}], [{t:1,weight:0},{t:1,weight:1}], [{t:2,weight:0},{t:1,weight:1}]]) assert.throws(() => validateExpressionTracks([{expression:'happy',keys}]));
assert.throws(() => validateExpressionTracks([...tracks, ...tracks]), /unique/);
const character = createCharacterEntry({id:'alice',model:'sakura-vrm',expressions:tracks});
const reopened = createCharacterEntry(JSON.parse(JSON.stringify(character)));
assert.deepEqual(reopened.expressions, tracks);
character.expressions[0].keys[1].weight = 0;
assert.equal(tracks[0].keys[1].weight, 1, 'documents own their keys');
assert.equal(reopened.expressions[0].keys[1].weight, 1);
assert.equal(Object.hasOwn(createCharacterEntry({}), 'expressions'), false, 'old documents keep their shape');
console.log('PASS facial interpolation, invalid LLM data, avatar capabilities and persistence');
