import assert from 'node:assert/strict';
import { normalizeSceneCameras,resolveSceneCameras,detachSceneCamera,reconcileSceneCameraEdits } from '../src/scene-cameras.js';
import { createShotAuthoringDocument,readShotAuthoringDocument } from '../src/shot-authoring.js';
import { createShot,cutAtFrame } from '../src/cuts.js';
import { sampleAt } from '../src/sample-at.js';
import { cameraMoveAt } from '../src/camera-move.js';

const framing = x=>({pos:{x,y:1.6,z:5},yaw:0,pitch:0,fovDeg:40});
const cameras=normalizeSceneCameras([{id:'approach',name:'Approach',cameraKeys:[{id:'a',frame:0,framing:framing(0)},{id:'b',frame:72,framing:framing(2)}]},
  {id:'reaction',name:'Reaction',cameraKeys:[{id:'c',frame:0,framing:framing(-4)}]}]);
const shot=(id,start,end,cameraId)=>({...createShot(id,start,end),id,cameraId});
const shots=resolveSceneCameras([shot('walk',0,71,'approach'),shot('reply',72,143,'reaction'),shot('reuse',144,191,'approach')],cameras);
const scene={frameCount:192,subject:{x:1,z:2}};
assert.equal(sampleAt(scene,shots[0],0).camera.pos.x,0);
assert.equal(sampleAt(scene,shots[1],72).camera.pos.x,-4,'cut selects the next camera instantly');
assert.equal(sampleAt(scene,shots[2],144).camera.pos.x,0,'reuse starts on the local camera clock');
for (const f of [1,12,23,47]) assert.deepEqual(sampleAt(scene,shots[2],144+f).camera,sampleAt(scene,shots[0],f).camera,'shorter shots retain the complete easing curve');
const split=cutAtFrame([shots[0]],'walk',30,framing(0));
const splitResolved=resolveSceneCameras(split,cameras);
for(const f of [29,30,31,70]) assert.deepEqual(sampleAt(scene,splitResolved[f<30?0:1],f).camera,sampleAt(scene,shots[0],f).camera,'split preserves camera continuity and its local offset');
const detached=detachSceneCamera(shots[2],scene.subject);
for(let f=144;f<192;f++) assert.deepEqual(sampleAt(scene,detached,f).camera,sampleAt(scene,shots[2],f).camera,'detaching a partial move keeps every export frame');
const edited={...shots[0],cameraKeys:shots[0].cameraKeys.map((key,i)=>i===0?{...key,framing:framing(3)}:key)};
const changed=reconcileSceneCameraEdits({shots,cameras},{shots:[edited,...shots.slice(1)],cameras});
assert.equal(changed[0].cameraKeys[0].framing.pos.x,3);
assert.equal(resolveSceneCameras(shots,changed)[2].cameraKeys[0].framing.pos.x,3);
const moved={...shots[0],startFrame:10,endFrame:81};
assert.deepEqual(reconcileSceneCameraEdits({shots,cameras},{shots:[moved,...shots.slice(1)],cameras}),cameras,'cut timing does not retime camera definitions');
const document=createShotAuthoringDocument({shots,cameras,frameCount:192});
const loaded=readShotAuthoringDocument(JSON.parse(JSON.stringify(document))).state;
assert.deepEqual(loaded.cameras,cameras);
const restored=resolveSceneCameras(loaded.shots,loaded.cameras);
for(const f of [0,71,72,143,144,191]) assert.deepEqual(sampleAt(scene,restored.find(shot=>f>=shot.startFrame&&f<=shot.endFrame),f),sampleAt(scene,shots.find(shot=>f>=shot.startFrame&&f<=shot.endFrame),f));
const keys=[{frame:0,framing:framing(0),interpolation:'hold'},{frame:24,framing:framing(2)}];
const longCamera=normalizeSceneCameras([{id:'c'.repeat(120),cameraKeys:[{id:'k'.repeat(120),frame:12,framing:framing(0)},{id:'start',frame:24,framing:framing(1)}]}]);
const longShot=resolveSceneCameras([shot('s'.repeat(120),0,30,longCamera[0].id)],longCamera)[0];
assert(longShot.cameraKeys.every(key=>key.id.length<=120),'resolved IDs fit the agent contract');
assert.equal(new Set(longShot.cameraKeys.map(key=>key.id)).size,longShot.cameraKeys.length,'synthetic boundaries have distinct IDs');
assert.equal(cameraMoveAt(keys,scene.subject,23).pos.x,0);
assert.equal(cameraMoveAt(keys,scene.subject,24).pos.x,2);
console.log('PASS named cameras: hard cuts, independent local clocks, shared edits, split continuity, cropped moves, detachment and project persistence');
